CREATE USER IF NOT EXISTS BD_GITHUB_USER PASSWORD = '******' 
DEFAULT_ROLE = BD_SU_GITHUB_ADMIN_ROLE MUST_CHANGE_PASSWORD = FALSE
DEFAULT_WAREHOUSE = 'COMPUTE_WH';

GRANT ROLE BD_SU_GITHUB_ADMIN_ROLE TO USER BD_GITHUB_USER;

